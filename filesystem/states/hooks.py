# События:
#   remove  -- слой снят (один раз на слой);
#   attempt -- неудачная попытка снять слой (каждый раз);
#   fail    -- попытки кончились (один раз, в момент, когда кончились);
#   read    -- файл прочитан (каждый раз);
#   delete  -- файл удалён в сессии (каждый раз);
#   restore -- файл восстановлен «с диска».
EVENTS = ("remove", "attempt", "fail", "read", "delete", "restore")

# Действия, у которых остаток строки -- текст (say "Готово").
TEXT_ACTIONS = ("say", "log")

# Действия с одним путём (drop /home/a.dat).
PATH_ACTIONS = ("drop", "rename", "copy")

# add <слой> [аргументы]: добавить слой на файл.
ACTIONS = TEXT_ACTIONS + PATH_ACTIONS + ("add",)

# Подстановки {...}, доступные в любом тексте (say, log, ответы слоя).
# Слой может добавить свои (см. BaseState.placeholders), а значения его
# аргументов доступны по имени аргумента.
GLOBAL_PLACEHOLDERS = ("path", "name")